#!/usr/bin/env python3
"""Turn the upstream 32 KB reader ROM image into a C header for the Pico firmware."""
import sys

src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
assert len(data) == 32768, f"expected a 32 KB image, got {len(data)} bytes"
with open(dst, "w") as f:
    f.write("// Generated by tools/bin2h.py from upstream/upd7811-reader.bin (devinacker/upd7811-reader v1.0).\n")
    f.write("// Firmware that runs ON the uPD78C14; the Pico serves it as the external ROM.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("static const uint8_t reader_rom[32768] = {\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
